// ============================================================================
// db/pool.js — одно «окно» для общения с базой на весь проект
// ============================================================================
//
// Что такое пул соединений.
// Для каждого SQL-запроса серверу нужно открыться к PostgreSQL — это
// «соединение». Открывать его каждый раз заново медленно, поэтому pg
// держит несколько готовых соединений в очереди и выдаёт их по запросу:
// один запрос взял соединение, отработал, вернул обратно.
//
// Почему пул один.
// Если каждый модуль создаст свой new Pool(), свободных соединений у базы
// быстро не останется. Поэтому пул создаётся здесь ровно один раз, а все,
// кому нужна база, делают require('./db/pool') и получают готовый объект.

const { Pool } = require('pg');

// Адрес базы берём из переменной окружения, а не пишем в коде:
// postgres://tur:пароль@db:5432/tur_project
// (пользователь, пароль, хост-сервера, порт, имя базы).
// Значение задаёт docker-compose.yml, поэтому пароль не попадает в git.
const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
});

// Соединение в очереди может «протухнуть», пока ждёт (например, база
// перезапустилась). Тогда pg выбрасывает неисключенное событие «error».
// Без обработчика — весь процесс упадёт. Здесь же просто лог, сервер жив.
pool.on('error', (err) => {
  console.error('Неожиданная ошибка простаивающего соединения pg:', err.message);
});

// Отдаём объект тем, кто написал require('.../db/pool')
module.exports = pool;
