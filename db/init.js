// ============================================================================
// db/init.js — создаёт таблицы в PostgreSQL (запускается один раз, руками)
// ============================================================================
//
// Что делает: подключается к базе и выполняет SQL из переменной initSQL,
// то есть создаёт три таблицы (users, tours, bookings) и индексы к ним.
//
// Как запускать:  node db/init.js   (или npm run db:init)
// Этот файл НЕ часть сервера — сервер его не вызывает. Его запускают один
// раз при первом развёртывании проекта, чтобы подготовить пустую базу.
//
// Почему можно запускать повторно.
// Везде написано IF NOT EXISTS: «создать, если ещё не существует». Второй
// запуск ничего не сломает и не задвоит таблицы — просто пропустит готовое.
//
// Структура таблиц (соответствует DATA_CONTRACT.md):
//   users      — регистрации, входы, роли (user / manager / admin), блокировки
//   tours      — пакетные туры (перелёт + отель + трансфер в одном продукте)
//   bookings   — заявки на бронирование (клиент сам или через менеджера)

const pool = require('./pool');

// ВНИМАНИЕ: внутри SQL-строки комментарии пишутся как «--» (два минуса),
// а не как «//» — это правило PostgreSQL, а не JavaScript.
// Несколько операторов в одном query() выполняются одним пакетом.
const initSQL = `
  -- ─── users: кто заходит на сайт и что ему разрешено ───
  CREATE TABLE IF NOT EXISTS users (
    -- IDENTITY — счётчик: база сама выдаёт 1, 2, 3... при каждой вставке
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- UNIQUE — два аккаунта на один email создать нельзя
    email       VARCHAR(255) UNIQUE NOT NULL,
    -- НЕ сам пароль, а его хэш от bcrypt (~60 символов). Наружу не отдаём.
    password_hash  VARCHAR(255) NOT NULL,
    full_name   VARCHAR(150) NOT NULL,
    phone       VARCHAR(30) NOT NULL,
    -- DEFAULT 'user': роль можно не указывать при вставке.
    -- CHECK не даст записать role = 'superuser' — база откажет.
    role        VARCHAR(20) NOT NULL DEFAULT 'user'
                CHECK (role IN ('user', 'manager', 'admin')),
    -- is_blocked. middlewares/auth.js смотрит сюда при каждом запросе:
    -- если true — разлогинивает, даже если пароль ввели верно.
    is_blocked  BOOLEAN NOT NULL DEFAULT FALSE,
    -- now() — дата сервера в момент вставки строки, вручную её ставить не нужно
    created_at  TIMESTAMP NOT NULL DEFAULT now()
  );

  -- ─── tours: пакетные туры (перелёт + отель + трансфер) ───
  CREATE TABLE IF NOT EXISTS tours (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          VARCHAR(200) NOT NULL,
    country        VARCHAR(100) NOT NULL,
    city           VARCHAR(100) NOT NULL,
    nights         INTEGER NOT NULL,
    -- CHECK: rating обязан быть от 1.0 до 5.0, иначе строка не вставится
    rating         DECIMAL(2,1) CHECK (rating >= 1.0 AND rating <= 5.0),
    image          VARCHAR(255) NOT NULL,
    description    TEXT NOT NULL,
    flight_info    VARCHAR(255) NOT NULL,
    flight_price   INTEGER NOT NULL,
    hotel_name     VARCHAR(150) NOT NULL,
    -- Только 3, 4 или 5 звёзд — «2» или «7» база не примет
    hotel_stars    INTEGER NOT NULL CHECK (hotel_stars IN (3, 4, 5)),
    hotel_info     VARCHAR(255) NOT NULL,
    hotel_price    INTEGER NOT NULL,
    transfer_info  VARCHAR(255) NOT NULL,
    transfer_price INTEGER NOT NULL,
    -- Итоговая цена. db/seed.js считает её как сумму трёх цен выше,
    -- но админ может задать и вручную — например, со скидкой за пакет.
    total_price    INTEGER NOT NULL,
    -- true — тур виден в каталоге; false — скрыт, но остаётся в базе
    is_active      BOOLEAN NOT NULL DEFAULT TRUE
  );

  -- ─── bookings: заявки на бронирование ───
  CREATE TABLE IF NOT EXISTS bookings (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- REFERENCES = внешний ключ (FK): ссылка на реальную строку другой таблицы.
    -- Нельзя создать заявку на несуществующий тур, и нельзя удалить тур,
    -- пока на него есть заявки — база не позволит и в том, и в другом случае.
    tour_id       INTEGER NOT NULL REFERENCES tours(id),
    -- user_id БЕЗ NOT NULL, то есть может быть пустым (NULL).
    -- NULL = заявку оформил менеджер, а не клиент сам через сайт.
    user_id       INTEGER REFERENCES users(id),
    -- И наоборот: NULL, если клиент бронировал самостоятельно
    manager_id    INTEGER REFERENCES users(id),
    client_name   VARCHAR(150) NOT NULL,
    client_phone  VARCHAR(30) NOT NULL,
    comment       TEXT,
    -- Три состояния заявки. CHECK закрывает путь к опечатке вроде 'done'
    status        VARCHAR(20) NOT NULL DEFAULT 'new'
                CHECK (status IN ('new', 'confirmed', 'cancelled')),
    created_at    TIMESTAMP NOT NULL DEFAULT now()
  );

  -- ─── Индексы: почему поиск становится быстрее ───
  -- Без индекса база перечитывает ВСЕ строки таблицы подряд, пока найдёт
  -- подходящие. Индекс — это заранее отсортированный указатель, как оглавление
  -- в книге: база сразу переходит к нужным строкам.
  -- Платой за это — чуть медленнее вставка и место на диске.
  CREATE INDEX IF NOT EXISTS idx_tours_country  ON tours(country);
  CREATE INDEX IF NOT EXISTS idx_tours_city     ON tours(city);
  CREATE INDEX IF NOT EXISTS idx_tours_total    ON tours(total_price);
  CREATE INDEX IF NOT EXISTS idx_bookings_user       ON bookings(user_id);
  CREATE INDEX IF NOT EXISTS idx_bookings_manager    ON bookings(manager_id);
`;

// ============================================================================
// init() — подключается к базе, выполняет SQL, закрывает соединение.
// ============================================================================
//
// pool.connect() — берёт одно соединение из пула. Это как «арендовать
// ключ» — соединение принадлежит клиенту до тех пор, пока не вызовем
// client.release(). Если забыть отпустить, пул постепенно кончится.
//
// try / catch / finally — шаблон, чтобы соединение вернулось в пул
// даже если SQL упал с ошибкой. В finally оно возвращается в любом случае.
async function init() {
  // Берём «ключ» из пула
  const client = await pool.connect();
  try {
    // Выполняем весь пакет SQL сразу — база создаст таблицы и индексы
    await client.query(initSQL);
    console.log('✅ Все таблицы созданы');
  } catch (err) {
    console.error('❌ Ошибка инициализации БД:', err.message);
    process.exit(1);  // дальше работать бессмысленно — выходим
  } finally {
    // Всегда возвращаем соединение в пул, даже если была ошибка
    client.release();
  }
}

// Запускаем функцию при запуске этого файла:  node db/init.js
init();
