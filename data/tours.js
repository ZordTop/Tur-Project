// ============================================================================
// findTourById(id) — поиск одного тура по его уникальному идентификатору
// ============================================================================
//
// НАЗНАЧЕНИЕ
// Вызывается только из routes/tours.js, маршрут GET /tours/:id:
//   const tour = findTourById(req.params.id);
//
// ПОЧЕМУ Number(id)
// Все параметры URL (req.params) приходят как строки. Например, по адресу
// /tours/1 значение req.params.id === '1' (строка). Массив const tours
// хранит id как числа (Number), поэтому без Number(id) сравнение
// '1' === 1 вернуло бы false. Это частая ловушка при работе с маршрутами Express.
//
// ЧТО ВОЗВРАЩАЕТ
// - если тур найден — объект тура (с полями id, title, price и т.д.)
// - если тур не найден (например, /tours/999) — undefined
//
// routes/tours.js проверяет:
//   if (!tour) { return next(); }   // передаёт управление дальше → 404-хендлер
//
// ФОРМАТИРОВАНИЕ В ШАБЛОНЕ
// Цена в шаблоне tour.ejs отображается так:
//   <%= tour.price.toLocaleString('ru-RU') %> ₽
// Это добавляет пробелы между разрядами: 45000 → "45 000 ₽"
function findTourById(id) {
  // .find() перебирает массив слева направо и возвращает ПЕРВЫЙ элемент,
  // для которого условие истинно. Если такой не найден — вернёт undefined.
  return tours.find((tour) => tour.id === Number(id));
}

