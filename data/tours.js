//   tours        — сам массив (нужен для GET /tours, чтобы отрисовать весь список)
//   findTourById — функция поиска (нужна для GET /tours/:id)
// Экспорт через объект с двумя ключами, а не «по одному», чтобы потребителю
// хватало одного require() с деструктуризацией.
module.exports = { tours, findTourById };
